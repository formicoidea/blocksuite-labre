import { BlockSuiteError, ErrorCode } from '@labre/global/exceptions';
import { generateKeyBetween } from 'fractional-indexing';

/** Bound on the steps moving a key towards b, see the loop below. */
const MAX_PREFIX_STEPS = 16;

/**
 * Longest key `a` or `b` accepted. The package's `midpoint` recurses once
 * per character of a run of top digits (`z`), so a forged key such as
 * `a0` + `z` x 20000 overflowed the stack with a `RangeError`. Measured
 * on V8 (Node 24, Chromium): the overflow starts from about 5700 characters
 * on a cold stack, 10000 once optimised, so the bound sits under the cold
 * figure. Legitimate keys stay far below it in normal use (20000 inserts:
 * 37 characters appending or prepending, about 300 right after the first
 * row); the one pattern that grows them is inserting again and again right
 * before the same row, about one character per six inserts, 4035 after
 * 20000. That series overflows the stack a few thousand inserts later
 * anyway: past the bound it fails earlier, with a named error.
 */
const MAX_KEY_LENGTH = 4096;

function hasSamePrefix(a: string, b: string) {
  return a.startsWith(b) || b.startsWith(a);
}

/**
 * generate a key between a and b, the result key is always satisfied with a < result < b.
 * the key always has a random suffix, so there is no need to worry about collision.
 *
 * make sure a and b are generated by this function.
 *
 * @param customPostfix custom postfix for the key, only letters and numbers are allowed
 */
export function generateFractionalIndexingKeyBetween(
  a: string | null,
  b: string | null
) {
  const randomSize = 32;
  function postfix(length: number = randomSize) {
    const chars =
      '123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
    const values = new Uint8Array(length);
    crypto.getRandomValues(values);
    let result = '';
    for (let i = 0; i < length; i++) {
      result += chars.charAt(values[i] % chars.length);
    }
    return result;
  }

  // The message never quotes the key: it may be 100 KB of forged content.
  if (
    (a !== null && a.length > MAX_KEY_LENGTH) ||
    (b !== null && b.length > MAX_KEY_LENGTH)
  ) {
    throw new BlockSuiteError(
      ErrorCode.DefaultRuntimeError,
      `fractional index key longer than ${MAX_KEY_LENGTH} characters`
    );
  }

  if (a !== null && b !== null && a >= b) {
    throw new Error('a should be smaller than b');
  }

  // get the subkey in full key
  // e.g.
  // a0xxxx -> a
  // a0x0xxxx -> a0x
  function subkey(key: string | null) {
    if (key === null) {
      return null;
    }
    if (key.length <= randomSize + 1) {
      // no subkey
      return key;
    }
    const splitAt = key.substring(0, key.length - randomSize - 1);
    return splitAt;
  }

  const aSubkey = subkey(a);
  const bSubkey = subkey(b);

  if (aSubkey === null && bSubkey === null) {
    // generate a new key
    return generateKeyBetween(null, null) + '0' + postfix();
  } else if (aSubkey === null && bSubkey !== null) {
    // generate a key before b
    return generateKeyBetween(null, bSubkey) + '0' + postfix();
  } else if (bSubkey === null && aSubkey !== null) {
    // generate a key after a
    return generateKeyBetween(aSubkey, null) + '0' + postfix();
  } else if (aSubkey !== null && bSubkey !== null) {
    // generate a key between a and b
    if (hasSamePrefix(aSubkey, bSubkey) && a !== null && b !== null) {
      // conflict, if the subkeys are the same, generate a key between fullkeys
      const middle = generateKeyBetween(a, b);
      let key = middle;
      // The postfix would decide the order, and could sort the key after b,
      // if b continues with key + '0': move the key closer to b until it
      // no longer prefixes b that way (#655, upstream AFFiNE#15709). Only new
      // keys change; stored keys are compared as before.
      let steps = 0;
      while (b.startsWith(key + '0')) {
        // A forged b (`a10` + `10` x N) needs one step per repetition,
        // quadratic in its length, so the loop is bounded. Legitimate keys
        // reach the bound too: inserting again and again right after the
        // first row needs 32 steps by the 150th insert, 128 by the 600th.
        // Past it, aim at a instead: generateKeyBetween(a, middle) plus a
        // random postfix, so two peers inserting at the same place still get
        // distinct keys. A bare, deterministic middle would give them the
        // same key, and a later insert between the two would throw.
        if (++steps > MAX_PREFIX_STEPS) {
          const towardsA = generateKeyBetween(a, middle) + '0' + postfix();
          // Required, not decorative: midpoint can return a prefix of middle
          // (its `b.slice(0, 1)` branch), and that prefix plus the postfix
          // may sort after b. Only this check keeps the order; the bare
          // middle is the fallback that is always in order.
          if (a < towardsA && towardsA < b) return towardsA;
          return middle;
        }
        key = generateKeyBetween(key, b);
      }
      return key + '0' + postfix();
    } else {
      return generateKeyBetween(aSubkey, bSubkey) + '0' + postfix();
    }
  }
  throw new Error('Never reach here');
}
