/**
 * The business-domain overlay of the architecture map (ADR 0040, amendment
 * of 2026-10-23): `architecture/domain.c4`, projected from
 * `architecture/domains.json` by `yarn architecture`, and the report the
 * weekly routine reads (procedure: `architecture/domains-routine.md`).
 *
 * The hierarchy of the map is the repository's; a domain is not. A file may
 * serve two domains, so a domain is a scored, multi-valued metadata on the
 * elements of code.c4, never a tag and never a parent. Two halves:
 * - the probable half is `domains.json`, written by the weekly Claude Code
 *   routine and reviewed in its PR: the domain list, and rules mapping a
 *   path prefix (a folder or a file-name prefix) to domain weights. Rules
 *   listed under `validated` were confirmed by a human; the routine never
 *   changes or drops them, so a reviewed answer stays put;
 * - the exact half is this projection: a file takes the weights of the
 *   longest rule prefix it matches (normalised to 1), and an element's score
 *   for a domain is the mean over its files, unmatched files counting as 0.
 *   An element keeps the domains above the thresholds below. Same inputs,
 *   same file: `yarn architecture --check` holds it like code.c4.
 *
 * The report (`yarn architecture --domains`) is the routine's input: files
 * no rule matches, rules matching no file, and communities of the
 * folder-grain import graph (label propagation) with the folders whose
 * dominant domain differs from their community's, a signal for the reviewer
 * rather than an error.
 */

// An element shows in a domain's view from MIN_SCORE of its files, or from
// MIN_FILES files: a grab-bag folder (the `src/` of `affine/all`) holds a real
// share of several domains without any reaching MIN_SCORE.
// ponytail: fixed thresholds, per-domain ones if a domain floods its view
const MIN_SCORE = 0.15;
const MIN_FILES = 5;
// ponytail: fixed hub cut, a degree percentile if the map grows tenfold
const HUB_DEGREE = 20;

const quote = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const byKey = (a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);

/** file -> { domain: weight } normalised to 1, or null when no rule matches. */
function weightsOf(file, rules) {
  let best = null;
  for (const prefix of Object.keys(rules))
    if (file.startsWith(prefix) && (!best || prefix.length > best.length))
      best = prefix;
  if (!best) return null;
  const weights = Object.entries(rules[best]);
  const total = weights.reduce((sum, [, w]) => sum + w, 0);
  return total > 0
    ? Object.fromEntries(weights.map(([d, w]) => [d, w / total]))
    : null;
}

/** Throws on a domains.json the projection cannot read. */
export function checkSpec(spec) {
  const domains = new Set(Object.keys(spec.domains ?? {}));
  for (const id of domains)
    if (!/^[a-z][a-z0-9-]*$/.test(id))
      throw new Error(`domains.json: domain id ${id} is not kebab-case`);
  for (const [prefix, weights] of Object.entries(spec.rules ?? {}))
    for (const [domain, weight] of Object.entries(weights))
      if (!domains.has(domain) || !(weight > 0))
        throw new Error(
          `domains.json: rule ${prefix} gives ${weight} to ${domain}, which is not a declared domain with a positive weight`
        );
  for (const prefix of spec.validated ?? [])
    if (!spec.rules?.[prefix])
      throw new Error(`domains.json: validated ${prefix} is not a rule`);
}

/** element fqn -> [[domain, score]] sorted by score, then id. */
function scores(owners, spec) {
  const sums = new Map();
  for (const [file, elements] of owners) {
    const weights = weightsOf(file, spec.rules ?? {});
    for (const fqn of elements) {
      const sum = sums.get(fqn) ?? { files: 0, domains: new Map() };
      sum.files += 1;
      for (const [d, w] of Object.entries(weights ?? {}))
        sum.domains.set(d, (sum.domains.get(d) ?? 0) + w);
      sums.set(fqn, sum);
    }
  }
  const out = new Map();
  for (const [fqn, { files, domains }] of sums) {
    const kept = [...domains]
      .filter(([, w]) => w / files >= MIN_SCORE || w >= MIN_FILES)
      .map(([d, w]) => [d, Math.round((w / files) * 100) / 100])
      .sort((a, b) => b[1] - a[1] || byKey(a, b));
    if (kept.length) out.set(fqn, kept);
  }
  return out;
}

/**
 * The text of `architecture/domain.c4`. `owners` maps each file of the map
 * to the fqns of the elements it counts in (its unit and its folder).
 */
export function emitDomains(owners, spec, { generator, command }) {
  checkSpec(spec);
  const lines = [
    `// GENERATED by ${generator} from architecture/domains.json and the`,
    `// files of code.c4 (ADR 0040, amendment of 2026-10-23). Never edit by`,
    `// hand: the weekly routine edits domains.json, \`${command}\``,
    `// projects it here. Scores are probable; the hierarchy and the edges of`,
    `// code.c4 are exact.`,
    'model {',
  ];
  for (const [fqn, kept] of [...scores(owners, spec)].sort(byKey)) {
    lines.push(`  extend ${fqn} {`, '    metadata {');
    lines.push(`      domain [${kept.map(([d]) => quote(d)).join(', ')}]`);
    for (const [d, s] of kept)
      lines.push(`      domain_${d.replace(/-/g, '_')} '${s.toFixed(2)}'`);
    lines.push('    }', '  }');
  }
  lines.push('}', '', 'views {');
  for (const [id, description] of Object.entries(spec.domains).sort(byKey))
    lines.push(
      `  view domain-${id} {`,
      `    title ${quote(`Domain: ${id}`)}`,
      `    description ${quote(`${description} Scored overlay (domains.json), not a parent.`)}`,
      `    include * where metadata.domain is ${quote(id)}`,
      '    exclude * -> * where kind is imports',
      '  }'
    );
  lines.push('}', '');
  return lines.join('\n');
}

/** Label propagation over an undirected weighted graph; node -> community. */
function communities(edges) {
  const adjacency = new Map();
  const link = (a, b, w) => {
    if (!adjacency.has(a)) adjacency.set(a, new Map());
    adjacency.get(a).set(b, (adjacency.get(a).get(b) ?? 0) + w);
  };
  for (const { from, to, all } of edges) {
    link(from, to, all);
    link(to, from, all);
  }
  // A hub (shared utils, the DI container) is imported from everywhere and
  // would pull every folder into one community: it keeps its own label and
  // passes none.
  const hubs = new Set(
    [...adjacency].filter(([, n]) => n.size >= HUB_DEGREE).map(([h]) => h)
  );
  for (const [node, neighbours] of adjacency)
    for (const hub of hubs) if (node !== hub) neighbours.delete(hub);
  const nodes = [...adjacency.keys()].filter(n => !hubs.has(n)).sort();
  const label = new Map(nodes.map(n => [n, n]));
  // ponytail: synchronous order and a 50-pass cap; Leiden if the groups
  // stop reading as modules
  for (let pass = 0; pass < 50; pass += 1) {
    let changed = false;
    for (const node of nodes) {
      const tally = new Map();
      if (!adjacency.get(node).size) continue;
      for (const [other, w] of adjacency.get(node))
        tally.set(label.get(other), (tally.get(label.get(other)) ?? 0) + w);
      const [best] = [...tally].sort((a, b) => b[1] - a[1] || byKey(a, b))[0];
      if (best !== label.get(node)) {
        label.set(node, best);
        changed = true;
      }
    }
    if (!changed) break;
  }
  return { label, hubs };
}

/** Markdown report for the routine and its PR body. */
export function domainReport(owners, spec, folderEdges) {
  checkSpec(spec);
  const rules = spec.rules ?? {};
  const files = [...owners.keys()].sort();
  const unmatched = files.filter(f => !weightsOf(f, rules));
  const stale = Object.keys(rules)
    .filter(prefix => !files.some(f => f.startsWith(prefix)))
    .sort();
  const scored = scores(owners, spec);
  const size = new Map();
  for (const elements of owners.values())
    for (const fqn of elements) size.set(fqn, (size.get(fqn) ?? 0) + 1);
  const top = fqn => scored.get(fqn)?.[0]?.[0] ?? '(none)';

  // bundles have no file here: their domains are the library's overlay
  const elements = new Set([...owners.values()].flat());
  const { label, hubs } = communities(
    folderEdges.filter(e => elements.has(e.from) && elements.has(e.to))
  );
  const groups = new Map();
  for (const [node, l] of label)
    groups.set(l, [...(groups.get(l) ?? []), node]);
  const out = [
    `## Domain overlay report`,
    '',
    `${files.length - unmatched.length}/${files.length} files matched by ${Object.keys(rules).length} rules (${(spec.validated ?? []).length} validated), ${scored.size} elements scored.`,
    '',
    `### Files no rule matches (${unmatched.length})`,
    '',
    ...unmatched.map(f => `- ${f}`),
    '',
    `### Rules matching no file (${stale.length})`,
    '',
    ...stale.map(p => `- ${p}`),
    '',
    '### Import communities (label propagation, folder grain)',
    '',
    `Hubs left out (${HUB_DEGREE}+ neighbours): ${[...hubs].sort().join(', ') || 'none'}.`,
    '',
  ];
  for (const members of [...groups.values()]
    .filter(m => m.length > 1)
    .sort((a, b) => b.length - a.length || byKey(a, b))) {
    const tally = new Map();
    for (const m of members)
      for (const [d, s] of scored.get(m) ?? [])
        tally.set(d, (tally.get(d) ?? 0) + s * size.get(m));
    const dominant =
      [...tally].sort((a, b) => b[1] - a[1] || byKey(a, b))[0]?.[0] ?? '(none)';
    const outliers = members.filter(m => top(m) !== dominant);
    out.push(
      `- **${dominant}**, ${members.length} folders: ${members.sort().join(', ')}`
    );
    if (outliers.length)
      out.push(
        `  - off-domain: ${outliers.map(m => `${m} (${top(m)})`).join(', ')}`
      );
  }
  out.push('');
  return out.join('\n');
}
